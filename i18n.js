    const SUPPORTED = Object.keys(DICTS);
    const DEFAULT_LANG = 'zh-TW';
    const STORAGE_KEY = 'bazi_lang';

    function detectLang() {
        try {
            const saved = localStorage.getItem(STORAGE_KEY);
            if (saved && DICTS[saved]) return saved;
        } catch (_) {}

        try {
            const q = new URLSearchParams(location.search).get('lang');
            if (q && DICTS[q]) return q;
        } catch (_) {}

        const nav = ((navigator.language || navigator.userLanguage || '') + '').toLowerCase();
        if (nav.startsWith('zh-tw') || nav.startsWith('zh-hk') || nav.startsWith('zh-mo')) return 'zh-TW';
        if (nav.startsWith('zh')) return 'zh-CN';
        if (nav.startsWith('en')) return 'en';
        return DEFAULT_LANG;
    }

    let currentLang = detectLang();

    // 立即设置 lang 属性，避免浏览器先用 zh-TW 字体渲染再切换导致的字形闪烁和布局抖动
    try { document.documentElement.setAttribute('lang', currentLang); } catch (_) {}

    function t(key) {
        const dict = DICTS[currentLang] || DICTS[DEFAULT_LANG];
        if (dict && dict[key] != null) return dict[key];
        return (DICTS[DEFAULT_LANG][key] != null) ? DICTS[DEFAULT_LANG][key] : key;
    }

    function applyI18n(root) {
        const scope = root || document;

        scope.querySelectorAll('[data-i18n]').forEach((el) => {
            el.textContent = t(el.getAttribute('data-i18n'));
        });
        scope.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
            el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
        });
        scope.querySelectorAll('[data-i18n-alt]').forEach((el) => {
            el.setAttribute('alt', t(el.getAttribute('data-i18n-alt')));
        });
        scope.querySelectorAll('[data-i18n-aria-label]').forEach((el) => {
            el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria-label')));
        });

        document.title = t('meta_title');
        document.documentElement.setAttribute('lang', currentLang);

        scope.querySelectorAll('[data-lang-option]').forEach((el) => {
            el.classList.toggle('active', el.getAttribute('data-lang-option') === currentLang);
        });
    }

    function setLanguage(lang) {
        if (!DICTS[lang] || lang === currentLang) return;
        currentLang = lang;
        try { localStorage.setItem(STORAGE_KEY, lang); } catch (_) {}
        applyI18n();
        document.dispatchEvent(new CustomEvent('i18n:change', { detail: { lang } }));
    }

    function getLanguage() {
        return currentLang;
    }

    global.I18N = {
        t,
        applyI18n,
        setLanguage,
        getLanguage,
        supportedLanguages: SUPPORTED
    };

    document.addEventListener('DOMContentLoaded', () => applyI18n());

    // 当页面从 iOS BFCache（返回/前进缓存）恢复时，重新从 localStorage 读取语言并刷新 DOM，
    // 避免切换语言后按返回键语言回退的问题（BFCache 会保留旧的 JS 内存状态）。
    window.addEventListener('pageshow', (e) => {
        if (!e.persisted) return;
        const saved = (() => { try { return localStorage.getItem(STORAGE_KEY); } catch (_) { return null; } })();
        if (saved && DICTS[saved] && saved !== currentLang) {
            currentLang = saved;
            applyI18n();
            document.dispatchEvent(new CustomEvent('i18n:change', { detail: { lang: currentLang } }));
        }
    });
